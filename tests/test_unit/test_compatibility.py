@pytest.mark.parametrize("module", sorted(OLD_NAMES))
def test_old_names_still_exist(module):
    imported = importlib.import_module(f"lecilab_behavior_analysis.{module}")
    missing = [name for name in OLD_NAMES[module] if not hasattr(imported, name)]
    assert missing == []


def test_figure_maker_names():
    import lecilab_behavior_analysis.figure_maker as fm

    for name in ["subject_progress_figure", "session_summary_figure", "make_temperature_humidity_figure"]:
        assert hasattr(fm, name)
